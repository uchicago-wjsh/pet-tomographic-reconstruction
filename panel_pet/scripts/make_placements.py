#!/usr/bin/env python3
"""
Generate the GATE genericRepeater placements file for the four detector panels.

Layout (world frame, all distances in mm):

    y ^                 primary plate (top)     y = +202.5
      |        +--------------------------------------+
      |        |                                      |
   side plate  |            40 x 40 x 40 cm           |  side plate
   x = -227.5  |                 FOV                  |  x = +227.5
      |        |                                      |
      |        +--------------------------------------+
      +------> x        primary plate (bottom)  y = -202.5
     z out of page (48 cm long for all four plates)

  * basic module : 12 x 12 crystals of 4 x 4 x 5 mm, no gaps -> 48 x 48 mm
                   face, 5 mm thick. Local frame: X = 5 mm depth,
                   Y = 48 mm, Z = 48 mm.
  * primary plates (top/bottom): 10 x 10 modules  -> 480 x 480 mm = 48 x 48 cm
                   rotated +90 deg about z so the 5 mm depth points along y.
                   Inner faces at y = +/-200 mm  -> 40 cm apart.
  * side plates (left/right)   : 10 (z) x 8 (y) modules -> 480 x 384 mm
                   = 48 x 38.4 cm, unrotated (depth already along x).
                   Inner faces at x = +/-225 mm -> 45 cm apart.

Module ID ranges (the order modules are written here is the order GATE
assigns level1 copy numbers):

      0 -  99  bottom primary plate
    100 - 199  top primary plate
    200 - 279  left side plate
    280 - 359  right side plate

Total 360 modules x 144 crystals = 51840 crystals.
"""
import argparse
from pathlib import Path

CRYSTAL_XY = 4.0          # mm, crystal face
CRYSTAL_DEPTH = 5.0       # mm, crystal thickness (overridable, see --crystal-depth)
N_CRYSTAL = 12            # 12 x 12 per module
MODULE_FACE = CRYSTAL_XY * N_CRYSTAL          # 48.0 mm
MODULE_DEPTH = CRYSTAL_DEPTH                  # 5.0 mm

PRIMARY_GAP = 400.0       # mm between the two primary plate inner faces
SIDE_GAP = 450.0          # mm between the two side plate inner faces

PRIMARY_NX = 10           # modules along x
PRIMARY_NZ = 10           # modules along z
SIDE_NY = 8               # modules along y
SIDE_NZ = 10              # modules along z

OUT = Path(__file__).resolve().parent.parent / "data" / "module.placements"


def centred(n: int, pitch: float):
    """n module centre offsets, symmetric about 0."""
    return [(i - (n - 1) / 2.0) * pitch for i in range(n)]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--crystal-depth", type=float, default=CRYSTAL_DEPTH,
                    help="crystal thickness in mm along the module's local x "
                         "(default 5.0). The module centres move OUTWARD with "
                         "it so the plate INNER faces stay at PRIMARY_GAP/2 and "
                         "SIDE_GAP/2 -- a thicker crystal must not eat the bore.")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    global MODULE_DEPTH
    MODULE_DEPTH = args.crystal_depth
    out_path = args.out

    rows = []   # (angle_deg, axis_x, axis_y, axis_z, tx, ty, tz, label)

    # --- primary plates: rotate +90 deg about z so local +x -> global +y ---
    # depth then runs along y; the 48 mm module face spans x and z.
    y_primary = PRIMARY_GAP / 2.0 + MODULE_DEPTH / 2.0        # 202.5
    for label, sign in (("bottom", -1.0), ("top", +1.0)):
        for x in centred(PRIMARY_NX, MODULE_FACE):
            for z in centred(PRIMARY_NZ, MODULE_FACE):
                rows.append((90.0, 0, 0, 1, x, sign * y_primary, z, label))

    # --- side plates: no rotation, local +x already along global x ---
    # the 48 mm module face spans y and z.
    x_side = SIDE_GAP / 2.0 + MODULE_DEPTH / 2.0              # 227.5
    for label, sign in (("left", -1.0), ("right", +1.0)):
        for y in centred(SIDE_NY, MODULE_FACE):
            for z in centred(SIDE_NZ, MODULE_FACE):
                rows.append((0.0, 0, 0, 1, sign * x_side, y, z, label))

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w") as f:
        f.write("###### GATE genericRepeater placements for the 4 detector panels\n")
        f.write("###### generated by scripts/make_placements.py -- do not edit by hand\n")
        f.write("###### col 1     : time (s, ignored by genericRepeater)\n")
        f.write("###### col 2     : rotation angle (deg)\n")
        f.write("###### col 3,4,5 : rotation axis\n")
        f.write("###### col 6,7,8 : translation x y z (mm)\n")
        f.write("Time        s\n")
        f.write("Rotation    deg\n")
        f.write("Translation mm\n")
        current = None
        for ang, ax, ay, az, tx, ty, tz, label in rows:
            if label != current:
                f.write(f"###### {label} plate\n")
                current = label
            f.write(f"0  {ang:6.1f}  {ax} {ay} {az}   "
                    f"{tx:9.3f} {ty:9.3f} {tz:9.3f}\n")

    # --- report ---
    n_primary = PRIMARY_NX * PRIMARY_NZ
    n_side = SIDE_NY * SIDE_NZ
    total = 2 * n_primary + 2 * n_side
    print(f"wrote {out_path}")
    print(f"  primary plate : {PRIMARY_NX} x {PRIMARY_NZ} modules = "
          f"{PRIMARY_NX*MODULE_FACE/10:.1f} x {PRIMARY_NZ*MODULE_FACE/10:.1f} cm"
          f"   ({n_primary} modules each)")
    print(f"  side plate    : {SIDE_NZ} x {SIDE_NY} modules = "
          f"{SIDE_NZ*MODULE_FACE/10:.1f} x {SIDE_NY*MODULE_FACE/10:.1f} cm"
          f"   ({n_side} modules each)")
    print(f"  modules total : {total}   crystals total : {total*N_CRYSTAL**2}")
    print(f"  crystal depth : {MODULE_DEPTH:.1f} mm  -> module centres at "
          f"y = +/-{PRIMARY_GAP/2 + MODULE_DEPTH/2:.1f}, "
          f"x = +/-{SIDE_GAP/2 + MODULE_DEPTH/2:.1f} mm")
    print(f"  mother volume must cover x +/-{SIDE_GAP/2 + MODULE_DEPTH:.1f}, "
          f"y +/-{PRIMARY_GAP/2 + MODULE_DEPTH:.1f}, "
          f"z +/-{max(PRIMARY_NZ, SIDE_NZ)*MODULE_FACE/2:.1f} mm")
    print(f"  primary inner faces at y = +/-{PRIMARY_GAP/2:.1f} mm "
          f"({PRIMARY_GAP/10:.0f} cm apart)")
    print(f"  side    inner faces at x = +/-{SIDE_GAP/2:.1f} mm "
          f"({SIDE_GAP/10:.0f} cm apart)")
    print(f"  side plate spans y = +/-{SIDE_NY*MODULE_FACE/2:.1f} mm "
          f"(fits inside the {PRIMARY_GAP/10:.0f} cm primary gap)")


if __name__ == "__main__":
    main()
